let lang = "en";
const listeners = [];

export function getLang() { return lang; }
export function t(key) { return STRINGS[lang][key] ?? STRINGS.en[key] ?? key; }
export function bodyName(name) { return STRINGS[lang]["body." + name] ?? name; }
export function onLangChange(fn) { listeners.push(fn); }

// Decimal comma in Spanish.
export function num(text) { return lang === "es" ? String(text).replace(/(\d)\.(\d)/g, "$1,$2") : String(text); }

export function setLang(next, root = globalThis.document) {
  lang = next === "es" ? "es" : "en";
  if (root) {
    root.documentElement.lang = lang;
    for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
    for (const el of root.querySelectorAll("[data-i18n-title]")) {
      el.title = t(el.dataset.i18nTitle); el.setAttribute("aria-label", t(el.dataset.i18nTitle));
    }
  }
  for (const fn of listeners) fn(lang);
}

export function initialLang() {
  try {
    const q = new URLSearchParams(globalThis.location?.search || "").get("lang");
    if (q === "es" || q === "en") return q;
    const saved = globalThis.localStorage?.getItem("gravity-lab-lang");
    if (saved === "es" || saved === "en") return saved;
  } catch { /* storage blocked: fall through to the default */ }
  return "en";
}
